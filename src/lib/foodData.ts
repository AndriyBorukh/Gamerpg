export function getRandomFoods(count: number): FoodItem[] {
    const shuffled = [...FOOD_DATABASE].sort(() => 0.5 - Math.random());
    return shuffled.slice(0, count);
}

export function getTavernFoodMenu(tavernId: string): FoodItem[] {
    // Deterministic random based on tavern ID
    let seed = 0;
    for (let i = 0; i < tavernId.length; i++) {
        seed += tavernId.charCodeAt(i);
    }
    
    // Seeded random number generator
    const random = () => {
        const x = Math.sin(seed++) * 10000;
        return x - Math.floor(x);
    };

    const menuSize = Math.floor(random() * 8) + 8; // 8 to 15 food items
    const shuffled = [...FOOD_DATABASE].sort(() => 0.5 - random());
    
    return shuffled.slice(0, menuSize);
}
