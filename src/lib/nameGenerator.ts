export function getRandomElement<T>(arr: T[], seed?: number): T {
    if (seed === undefined) {
        return arr[Math.floor(Math.random() * arr.length)];
    } else {
        const x = Math.sin(seed++) * 10000;
        const rand = x - Math.floor(x);
        return arr[Math.floor(rand * arr.length)];
    }
}

export function getGenderForName(name: string): 'male' | 'female' {
    if (!name) return 'male';
    const lowerName = name.toLowerCase();

    // Explicit female titles / honorifics
    const femalePrefixes = [
        'пані', 'княгиня', 'чародійка', 'відьма', 'ворожка', 'стрільчиня', 'цілителька', 
        'паладинка', 'бардеса', 'майстриня', 'травничиня', 'розбійниця', 'володарка', 
        'амазонка', 'нишпорка', 'королева', 'лицарка', 'мавка', 'німфа'
    ];
    for (const prefix of femalePrefixes) {
        if (lowerName.includes(prefix)) return 'female';
    }

    // Explicit male titles / honorifics
    const malePrefixes = [
        'пан ', 'князь', 'астролог', 'ветеран', 'бард', 'кухар', 'купець', 'монах', 
        'брат ', 'граф', 'король', 'лицар', 'чародій', 'маг ', 'друїд', 'алхімік', 
        'берсерк', 'священик', 'слідопит', 'гном', 'капітан', 'дід ', 'козак'
    ];
    for (const prefix of malePrefixes) {
        if (lowerName.includes(prefix)) return 'male';
    }

    const words = name.trim().split(/\s+/).map(w => w.toLowerCase());
    
    // Check known female names / endings
    const femaleNames = [
        'ольга', 'анна', 'ганна', 'євпраксія', 'предслава', 'рогніда', 'малуша', 'ірина', 'євдокія', 'марія', 'софія',
        'анастасія', 'єлизавета', 'катерина', 'варвара', 'марфа', 'соломія', 'юлія', 'олександра', 'олена', 'дарія',
        'дарина', 'ксенія', 'любов', 'надія', 'віра', 'людмила', 'мирослава', 'ярослава', 'богдана', 'владислава',
        'златослава', 'ростислава', 'зоряна', 'ярина', 'наталя', 'наталія', 'христина', 'оксана', 'тетяна', 'уляна',
        'мальва', 'лада', 'веселина', 'радослава', 'віталія', 'галина', 'марина', 'світлана', 'роксолана', 'ілона',
        'елірія', 'морріган', 'фрея', 'лея', 'нікс', 'одарка', 'любава', 'злата'
    ];

    for (const word of words) {
        if (femaleNames.includes(word)) return 'female';
    }

    // Check first name or last word
    const targetWord = words[0] || '';
    if (femaleNames.includes(targetWord)) return 'female';

    // Female endings in Ukrainian first names
    if (targetWord.endsWith('а') || targetWord.endsWith('я') || targetWord.endsWith('ія')) {
        // Exclude specific male names ending in a/я (Микита, Ілля, Сава, Хома, Кузьма, Фома, Лука)
        const maleExceptions = ['микита', 'ілля', 'сава', 'савва', 'хома', 'фома', 'кузьма', 'лука', 'ярема', 'микола', 'панас', 'опанас', 'назар', 'дарій', 'касіян', 'елеазар'];
        if (!maleExceptions.includes(targetWord)) {
            return 'female';
        }
    }

    return 'male';
}

export function generateRandomName(culture: CultureType = 'any', gender: 'male' | 'female' | 'any' = 'any', seed?: number): string {
    const cultures = culture === 'any' ? Object.keys(NAMES_DATA) as CultureType[] : [culture];
    const selectedCulture = getRandomElement(cultures, seed);
    
    const targetGender: 'male' | 'female' = gender === 'any' ? (getRandomElement([0, 1], seed) === 0 ? 'male' : 'female') : gender;
    
    // @ts-ignore
    const data = NAMES_DATA[selectedCulture];
    const firstNames: string[] = data[targetGender];
    const surnames: string[] = data.surnames;
    
    const firstName = getRandomElement(firstNames, seed ? seed + 1 : undefined);
    const surname = getRandomElement(surnames, seed ? seed + 2 : undefined);
    
    return firstName + " " + surname;
}

export function generateRandomCharacter(culture: CultureType = 'any', genderPreference: 'male' | 'female' | 'any' = 'any', seed?: number): {
    name: string;
    gender: 'male' | 'female';
    avatar: string;
    firstName: string;
    surname: string;
} {
    const targetGender: 'male' | 'female' = genderPreference === 'any' ? (getRandomElement([0, 1], seed) === 0 ? 'male' : 'female') : genderPreference;
    const cultures = culture === 'any' ? Object.keys(NAMES_DATA) as CultureType[] : [culture];
    const selectedCulture = getRandomElement(cultures, seed);

    // @ts-ignore
    const data = NAMES_DATA[selectedCulture];
    const firstNames: string[] = data[targetGender];
    const surnames: string[] = data.surnames;

    const firstName = getRandomElement(firstNames, seed ? seed + 1 : undefined);
    const surname = getRandomElement(surnames, seed ? seed + 2 : undefined);
    const avatarList = targetGender === 'male' ? MALE_AVATARS : FEMALE_AVATARS;
    const avatar = getRandomElement(avatarList, seed ? seed + 3 : undefined);

    return {
        name: `${firstName} ${surname}`,
        gender: targetGender,
        avatar,
        firstName,
        surname
    };
}
